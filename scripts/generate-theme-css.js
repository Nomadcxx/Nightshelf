#!/usr/bin/env node
/**
 * Write the theme CSS from utils/themes.js.
 *
 * The palettes and the CSS used to be maintained separately, which is how
 * Terminal ended up with surfaces byte-identical to Night. Now the registry is
 * the only place values are edited and this script derives the rest.
 *
 *   node scripts/generate-theme-css.js          # rewrite the generated blocks
 *   node scripts/generate-theme-css.js --check   # exit 1 if they are stale
 *
 * tests/themes.test.js runs the --check path, so drift fails CI rather than
 * shipping quietly.
 */
const fs = require('node:fs')
const path = require('node:path')
const { transformSync } = require('@babel/core')

const ROOT = path.join(__dirname, '..')
const START = '/* THEMES:START — generated by scripts/generate-theme-css.js. Do not edit by hand. */'
const END = '/* THEMES:END */'

function loadRegistry() {
  const file = path.join(ROOT, 'utils', 'themes.js')
  const { code } = transformSync(fs.readFileSync(file, 'utf8'), {
    filename: 'themes.js',
    presets: [['@babel/preset-env', { targets: { node: 'current' } }]]
  })
  const module = { exports: {} }
  new Function('module', 'exports', code)(module, module.exports)
  return module.exports
}

/** Replace the region between the markers, preserving everything around it. */
function spliceBlock(source, body, indent) {
  const pad = ' '.repeat(indent)
  const block = `${pad}${START}\n${body}\n${pad}${END}`
  const from = source.indexOf(START)
  if (from === -1) throw new Error('missing THEMES:START marker')
  const to = source.indexOf(END, from)
  if (to === -1) throw new Error('missing THEMES:END marker')
  return source.slice(0, from - indent) + block + source.slice(to + END.length)
}

function colourCss(THEMES) {
  const out = []
  for (const [id, theme] of Object.entries(THEMES)) {
    // Night doubles as :root so an unthemed document still has a palette.
    const selector = id === 'night' ? `:root,\n  html[data-theme='night']` : `html[data-theme='${id}']`
    const fg = theme.colors.fg
    out.push(`  /* ${theme.label} — ${theme.description} */`)
    out.push(`  ${selector} {`)
    out.push(`    color: rgb(${fg.join(', ')});`)
    for (const [token, rgb] of Object.entries(theme.colors)) {
      out.push(`    --color-${token}: ${rgb.join(' ')};`)
    }
    for (const [name, value] of Object.entries(theme.gradients)) {
      out.push(`    --gradient-${name}: ${value};`)
    }
    out.push('  }')
    out.push('')
  }
  out.pop()
  return out.join('\n')
}

function glassCss(THEMES) {
  const out = []
  out.push('/* Glass follows each theme\'s own canvas. A navy tint over a true-black')
  out.push('   canvas reads as a smear rather than as depth, so the tint, blur and')
  out.push('   saturation are all per-theme rather than global. */')
  for (const [id, theme] of Object.entries(THEMES)) {
    out.push(`html[data-theme='${id}'] {`)
    for (const [token, value] of Object.entries(theme.glass)) {
      out.push(`  --glass-${token}: ${value};`)
    }
    out.push('}')
  }
  return out.join('\n')
}

function main() {
  const check = process.argv.includes('--check')
  const { THEMES } = loadRegistry()

  const targets = [
    { file: path.join(ROOT, 'assets', 'tailwind.css'), body: colourCss(THEMES), indent: 2 },
    { file: path.join(ROOT, 'assets', 'motion.css'), body: glassCss(THEMES), indent: 0 }
  ]

  let stale = false
  for (const { file, body, indent } of targets) {
    const current = fs.readFileSync(file, 'utf8')
    const next = spliceBlock(current, body, indent)
    if (current === next) continue
    stale = true
    if (!check) {
      fs.writeFileSync(file, next)
      console.log(`updated ${path.relative(ROOT, file)}`)
    } else {
      console.error(`stale: ${path.relative(ROOT, file)}`)
    }
  }

  if (check && stale) {
    console.error('\nGenerated theme CSS is out of date. Run: node scripts/generate-theme-css.js')
    process.exit(1)
  }
  if (!stale) console.log('theme CSS already up to date')
}

if (require.main === module) main()

module.exports = { loadRegistry, colourCss, glassCss, START, END }
